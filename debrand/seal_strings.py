#!/usr/bin/env python3
"""Generate the sealed string table used by the native sanitizer and JNI bridge.

The point is that no identity word may exist as a contiguous byte run in the
artifact.  A compiler folded ``Sealed{literal}`` still emits the literal when the
object is not constant-initialised in a way it can prove, and it emitted it here;
so the plaintext lives only in this script, and the header it writes contains
ciphertext byte arrays.

Run from the repository root:

    python debrand/seal_strings.py

Then rebuild.  The generated header is checked in so that a build needs no
Python.
"""
from __future__ import annotations

import pathlib
import sys

# name -> plaintext.  Order matters only for readability; the generator assigns
# stable C++ constant names.
STRINGS: dict[str, str] = {
    "kTokenDataAdb": "/data/adb",
    "kTokenLsposed": "lsposed",
    "kTokenLspd": "lspd",
    "kTokenVector": "vector",
    "kTokenZygisk": "zygisk",
    "kTokenLsplant": "lsplant",
    "kTokenDobby": "dobby",
    "kTokenXposed": "xposed",
    "kTokenMagisk": "magisk",
    "kTokenKernelSu": "kernelsu",
    "kTokenApatch": "apatch",
    "kTokenRiru": "riru",
    "kTokenShamiko": "shamiko",
    # "xposed" is already a token; these two catch the fork-specific spelling and the
    # modern API library name, which some scanners look for on their own.
    "kTokenRobv": "robv",
    "kTokenLibXposed": "libxposed",
    "kLegacyXposedPrefix": "de.robv.android.xposed.",
    "kNativeBridgeKey": "org.matrix.vector.nativebridge.",
    "kNativeBridgeSignature": "org/matrix/vector/nativebridge/",
    "kBridgeServiceKey": "org.matrix.vector.service.",
    "kEntryClassKey": "org.matrix.vector.core.",
    "kResourcesSuperClass": "rt/dummy/XResourcesSuperClass",
    "kXResKey": "android.content.res.XRes",
    "kXResClassName": "android.content.res.XResources",
    "kTypedArraySuperClass": "rt/dummy/XTypedArraySuperClass",
}

MASK_KEY = 0x5A
MASK_STEP = 131
HEADER = pathlib.Path("native/include/common/sealed_strings.h")


def mask(index: int) -> int:
    return (MASK_KEY + index * MASK_STEP) & 0xFF


def emit() -> str:
    lines = [
        "/*",
        " * @generated by debrand/seal_strings.py -- do not edit by hand.",
        " *",
        " * Ciphertext of every identity-bearing string the native code needs.  Xor",
        " * with the position mask below to recover the plaintext at runtime.",
        " *",
        " * The arrays and the pointer `Open()` reads through are `volatile` on",
        " * purpose.  A plain `constexpr` array plus an inline `Open()` is folded at",
        " * -O2: the compiler evaluates the loop over known bytes and emits the",
        " * plaintext as an ordinary constant, which is exactly what this file exists",
        " * to avoid.  Volatile loads are observable, so they cannot be folded.",
        " */",
        "",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <string>",
        "",
        "namespace rtstr {",
        "",
        "/// Xor mask for byte `index` of any sealed run in this file.",
        "constexpr char Mask(std::size_t index) {",
        f"    return static_cast<char>(({MASK_KEY:#04x} + index * {MASK_STEP}u) & 0xFFu);",
        "}",
        "",
        "inline std::string Open(const volatile unsigned char *data, std::size_t size) {",
        "    std::string out(size, '\\0');",
        "    for (std::size_t i = 0; i < size; ++i) {",
        "        out[i] = static_cast<char>(data[i] ^ Mask(i));",
        "    }",
        "    return out;",
        "}",
        "",
    ]
    for name, plain in STRINGS.items():
        payload = [ord(ch) ^ mask(i) for i, ch in enumerate(plain)]
        body = ", ".join(f"0x{byte:02x}" for byte in payload)
        lines.append(f"inline const volatile unsigned char {name}[] = {{{body}}};")
        lines.append(f"inline constexpr std::size_t {name}Size = {len(plain)};")
        lines.append("")
    lines.append("}  // namespace rtstr")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    root = pathlib.Path(__file__).resolve().parent.parent
    target = root / HEADER
    text = emit()
    if target.exists() and target.read_text(encoding="utf-8") == text:
        print(f"unchanged: {HEADER}")
        return 0
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote: {HEADER} ({len(STRINGS)} strings)")
    # Round-trip: every payload must decode back to its plaintext.
    for name, plain in STRINGS.items():
        payload = [ord(ch) ^ mask(i) for i, ch in enumerate(plain)]
        decoded = "".join(chr(byte ^ mask(i)) for i, byte in enumerate(payload))
        assert decoded == plain, name
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
